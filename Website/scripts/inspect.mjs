import { chromium } from '@playwright/test';
import fs from 'node:fs/promises';
import path from 'node:path';
import { root } from './media.mjs';
const output = path.join(root, '.cache/visual-qa'); await fs.mkdir(output, { recursive: true });
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
const errors = [];
page.on('pageerror', e => errors.push(e.message));
await page.goto('http://127.0.0.1:4322/', { waitUntil: 'networkidle' });
await page.screenshot({ path: path.join(output, 'home-preview.png') });
await page.screenshot({ path: path.join(output, 'home-desktop.png'), fullPage: true });
const resources = await page.evaluate(() => performance.getEntriesByType('resource').map(e => ({ url: e.name, bytes: e.transferSize })));
const summary = { initialResourceBytes: resources.reduce((n, r) => n + r.bytes, 0), fullMediaRequests: resources.filter(r => /\.(mp4|mp3)(?:$|\?)/.test(r.url)), errors };
await page.locator('#theme-toggle').click();
await page.screenshot({ path: path.join(output, 'home-light.png'), fullPage: true });
await page.setViewportSize({ width: 390, height: 844 });
await page.goto('http://127.0.0.1:4322/');
await page.screenshot({ path: path.join(output, 'home-mobile.png'), fullPage: true });
await page.goto('http://127.0.0.1:4322/install/');
await page.screenshot({ path: path.join(output, 'install-mobile.png'), fullPage: true });
await page.setViewportSize({ width: 1440, height: 1000 });
await page.goto('http://127.0.0.1:4322/showcase/');
await page.screenshot({ path: path.join(output, 'showcase-desktop.png'), fullPage: true });
console.log(JSON.stringify(summary, null, 2));
await fs.writeFile(path.join(output, 'report.json'), JSON.stringify(summary, null, 2));
await browser.close();
